// Baut dist/reolink-app-card.js aus src/. dist/ nie von Hand bearbeiten.
// node scripts/build.mjs          einmal bauen
// node scripts/build.mjs --watch  bei jeder Änderung neu bauen
import * as esbuild from 'esbuild';

const options = {
  entryPoints: ['src/index.js'],
  outfile: 'dist/reolink-app-card.js',
  bundle: true,
  format: 'iife',
  target: 'es2020',
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: '/* Reolink App Card – https://github.com/niondevelop/reolink-app-card\n   Generated from src/ by scripts/build.mjs. Do not edit this file directly. */' },
  logLevel: 'info',
};

if (process.argv.includes('--watch')) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
} else {
  await esbuild.build(options);
}
